// lib/theme/theme-css.ts
// Generates the theme CSS (docs/design/redesign-2026-11/SPEC.md §1.2) from
// lib/theme/tokens.ts. global.css embeds this exact output between the
// `theme-css:start` / `theme-css:end` markers and a unit test
// (lib/theme/theme-css.test.ts) fails when the two drift. Four blocks:
//   :root                                   light
//   @media (prefers-color-scheme: dark)     dark, unless data-theme="light"
//   :root[data-theme="dark"]                dark, an explicit choice
//   .dark                                   dark, for NativeWind `dark:` variants
import { designHexVars, shadowVars, themeTokens, type ThemeTokenSet } from "@/lib/theme/tokens";

export const THEME_CSS_START = "/* theme-css:start (generated by lib/theme/theme-css.ts, do not edit) */";
export const THEME_CSS_END = "/* theme-css:end */";

function declarations(tokens: ThemeTokenSet, indent: string): string {
  return Object.entries(tokens)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join("\n");
}

function scheme(name: "light" | "dark"): ThemeTokenSet {
  return {
    ...designHexVars(name),
    ...themeTokens[name],
    "--shadow": shadowVars[name],
  };
}

export function buildThemeCss(): string {
  const light = scheme("light");
  const dark = scheme("dark");
  const lightBlock = `${declarations(light, "  ")}\n  --radius: 0.5rem;\n  color-scheme: light;`;
  const darkBody = (indent: string) => `${declarations(dark, indent)}\n${indent}color-scheme: dark;`;
  return [
    `:root {\n${lightBlock}\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${darkBody("    ")}\n  }\n}`,
    `:root[data-theme="dark"] {\n${darkBody("  ")}\n}`,
    `.dark {\n${declarations(dark, "  ")}\n}`,
  ].join("\n");
}

/** global.css text between the markers, or null when they are missing. */
export function extractThemeCss(globalCss: string): string | null {
  const start = globalCss.indexOf(THEME_CSS_START);
  const end = globalCss.indexOf(THEME_CSS_END);
  if (start === -1 || end === -1 || end < start) return null;
  return globalCss.slice(start + THEME_CSS_START.length, end).replace(/^\n/, "").replace(/\n$/, "");
}

export function embedThemeCss(globalCss: string): string {
  const block = `${THEME_CSS_START}\n${buildThemeCss()}\n${THEME_CSS_END}`;
  const start = globalCss.indexOf(THEME_CSS_START);
  const end = globalCss.indexOf(THEME_CSS_END);
  if (start === -1 || end === -1) return `${globalCss}\n${block}\n`;
  return globalCss.slice(0, start) + block + globalCss.slice(end + THEME_CSS_END.length);
}
